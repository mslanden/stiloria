def rgb(h):
    return ",".join(str(v) for v in hexrgb(h))

def group(name, bg, fg, deco):
    lines = [f"[Colors:{name}]", f"BackgroundAlternate={rgb(bg[1])}", f"BackgroundNormal={rgb(bg[0])}"]
    lines += [f"{k}={rgb(v)}" for k, v in sorted({**deco, **fg}.items())]
    return "\n".join(lines)

def scheme(m):
    problems = []
    parts = [f"# {m['name']}: {m['comment']}\n# Generated by tools/make_colors.py; edit that, not this file.",
             """[ColorEffects:Disabled]
Color=56,56,56
ColorAmount=0
ColorEffect=0
ContrastAmount=0.65
ContrastEffect=1
IntensityAmount=0.1
IntensityEffect=2

[ColorEffects:Inactive]
ChangeSelectionColor=true
Color=112,111,110
ColorAmount=0.025
ColorEffect=2
ContrastAmount=0.1
ContrastEffect=2
Enable=false
IntensityAmount=0
IntensityEffect=0"""]
    for name, bg in m["sets"].items():
        parts.append(group(name, bg, m["fg"], m["deco"]))
        for key in ("ForegroundNormal", "ForegroundInactive", "ForegroundLink", "ForegroundNegative", "ForegroundNeutral", "ForegroundPositive"):
            for b in bg:
                if contrast(m["fg"][key], b) < 4.5:
                    problems.append(f"{m['name']} {name}: {key} {m['fg'][key]} on {b} is {contrast(m['fg'][key], b):.2f}:1")
    c = m["complementary"]
    parts.append(group("Complementary", c["bg"], {**m["fg"], "ForegroundNormal": c["fg"], "ForegroundInactive": c["inactive"],
                                                    "ForegroundLink": c["link"], "ForegroundActive": c["link"]}, m["deco"]))
    s = m["selection"]
    sel_fg = {k: s["fg"] for k in m["fg"]}
    sel_fg["ForegroundInactive"] = s["inactive"]
    parts.append(group("Selection", s["bg"], sel_fg, m["deco"]))
    for b in s["bg"]:
        for key in ("fg", "inactive"):
            if contrast(s[key], b) < 4.5:
                problems.append(f"{m['name']} selection {key} {s[key]} on {b} is {contrast(s[key], b):.2f}:1")
    parts.append(f"[General]\nColorScheme={m['file']}\nName={m['name']}\nshadeSortColumn=true")
    parts.append("[KDE]\ncontrast=4")
    w = m["wm"]
    parts.append("[WM]\n" + "\n".join([f"activeBackground={rgb(w['activeBackground'])}", f"activeBlend={rgb(w['activeForeground'])}",
                                       f"activeForeground={rgb(w['activeForeground'])}", f"inactiveBackground={rgb(w['inactiveBackground'])}",
                                       f"inactiveBlend={rgb(w['inactiveForeground'])}", f"inactiveForeground={rgb(w['inactiveForeground'])}"]))
    return "\n\n".join(parts) + "\n", problems

all_problems = []
for mode in (DAY, NIGHT):
    text, problems = scheme(mode)
    (OUT / f"{mode['file']}.colors").write_text(text)
    all_problems += problems
    print("wrote", OUT / f"{mode['file']}.colors")
if all_problems:
    print("\n".join(all_problems))
    sys.exit(1)
print("all text meets 4.5:1")
